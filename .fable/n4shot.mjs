import { chromium } from "playwright";
const [out, base = "http://127.0.0.1:3471", theme = "light"] = process.argv.slice(2);
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: theme, geolocation: { latitude: 40.72, longitude: -77.89 }, permissions: ["geolocation"] });
const p = await ctx.newPage();
p.on("pageerror", e => console.log("PAGEERROR", e.message.slice(0, 200)));
await p.goto(base + "/?plan=loop", { waitUntil: "load", timeout: 90000 });
await p.waitForTimeout(6000);
await p.getByRole("radio", { name: "Loop from start" }).check({ force: true, timeout: 15000 }).catch(e => console.log("no loop tab", e.message.slice(0, 80)));
await p.waitForTimeout(3000);
await p.screenshot({ path: `${out}-setup.png` });
await p.getByRole("radio", { name: "To a destination" }).check({ force: true }).catch(() => {});
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}-dest.png` });
await p.getByTestId("ride-style-more").locator("summary").click().catch(e => console.log("no more", e.message.slice(0,60)));
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}-dest-more.png` });
await p.getByRole("radio", { name: "Loop from start" }).check({ force: true });
await p.waitForTimeout(1500);
const btn = p.getByTestId("compose-create");
console.log("button:", await btn.textContent().catch(() => "?"), await btn.getAttribute("class").catch(() => "?"));
await btn.click({ timeout: 10000 }).catch(e => console.log("no plan btn", e.message.slice(0, 80)));
await p.waitForTimeout(12000);
console.log("button after:", await btn.textContent().catch(() => "?"), await btn.getAttribute("class").catch(() => "?"), "disabled", await btn.isDisabled().catch(() => "?"));
const cards = await p.locator('[data-testid="planner-inspector"] [data-role], [data-testid="planner-inspector"] article').evaluateAll(els => els.slice(0, 5).map(e => e.textContent.slice(0, 40)));
console.log("cards:", JSON.stringify(cards));
await p.screenshot({ path: `${out}-planned.png` });
await b.close();
